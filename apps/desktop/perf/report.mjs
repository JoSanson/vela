import console from 'node:console';

const PASS = '✅';
const FAIL = '❌';

export const ms = (v) => (typeof v === 'number' ? `${v.toFixed(v < 10 ? 1 : 0)} ms` : String(v));
export const mb = (v) => (typeof v === 'number' ? `${v.toFixed(1)} MB` : String(v));
export const kb = (bytes) => `${(bytes / 1024).toFixed(1)} KB`;

export function printTable(rows) {
  const cols = ['Metric', 'Budget', 'Measured', 'Status'];
  const data = rows.map((r) => [r.metric, r.budget, r.measured, r.ok ? PASS : FAIL]);
  const widths = cols.map((c, i) => Math.max(c.length, ...data.map((d) => d[i].length)));
  const line = (cells) => cells.map((c, i) => c.padEnd(widths[i])).join('  ');
  console.info('');
  console.info(line(cols));
  console.info(widths.map((w) => '-'.repeat(w)).join('  '));
  for (const d of data) console.info(line(d));
  console.info('');
}

export function renderMarkdown({ rows, machine, details, methodology }) {
  const out = [];
  out.push('# Vela performance budgets');
  out.push('');
  out.push(
    `Generated by \`pnpm perf\` on ${machine.date}. Exit status: ${rows.every((r) => r.ok) ? 'all budgets met' : `${rows.filter((r) => !r.ok).length} budget(s) failed`}.`,
  );
  out.push('');
  out.push('| Metric | Budget | Measured | Status |');
  out.push('| --- | --- | --- | --- |');
  for (const r of rows) out.push(`| ${r.metric} | ${r.budget} | ${r.measured} | ${r.ok ? PASS : FAIL} |`);
  out.push('');
  out.push('## Machine');
  out.push('');
  out.push(`- CPU: ${machine.cpu} (${machine.cores} cores)`);
  out.push(`- RAM: ${machine.ramGB} GB`);
  out.push(`- OS: ${machine.os}`);
  out.push(
    `- Electron ${machine.electron} (Chromium ${machine.chrome}, Node ${machine.node}), Vela ${machine.appVersion}`,
  );
  out.push(`- Display: ${machine.display}`);
  out.push('');
  for (const d of details) {
    out.push(`## ${d.title}`);
    out.push('');
    out.push(...d.lines);
    out.push('');
  }
  out.push('## Methodology');
  out.push('');
  out.push(...methodology);
  out.push('');
  return out.join('\n');
}
